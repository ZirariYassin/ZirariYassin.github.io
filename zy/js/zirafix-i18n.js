  var KEY = "zy-lang";
  var lang = "fr";

  function t(key, vars) {
    var s = (D[lang] && key in D[lang]) ? D[lang][key] : (key in D.fr ? D.fr[key] : key);
    if (vars) Object.keys(vars).forEach(function (v) { s = s.split("{" + v + "}").join(vars[v]); });
    return s;
  }

  function apply(root) {
    root = root || document;
    root.querySelectorAll("[data-i18n]").forEach(function (el) { el.textContent = t(el.getAttribute("data-i18n")); });
    root.querySelectorAll("[data-i18n-attr]").forEach(function (el) {
      el.getAttribute("data-i18n-attr").split(";").forEach(function (pair) {
        var p = pair.split(":");
        el.setAttribute(p[0].trim(), t(p[1].trim()));
      });
    });
  }

  function setLang(next, opts) {
    lang = next === "en" || next === "nl" ? next : "fr";
    document.documentElement.lang = lang;
    apply();
    document.title = t("meta.title");
    var md = document.querySelector('meta[name="description"]');
    if (md) md.setAttribute("content", t("meta.desc"));
    document.querySelectorAll("[data-lang]").forEach(function (b) {
      b.setAttribute("aria-pressed", String(b.getAttribute("data-lang") === lang));
    });
    if (!opts || opts.persist !== false) { try { localStorage.setItem(KEY, lang); } catch (e) {} }
    document.dispatchEvent(new CustomEvent("langchange", { detail: lang }));
  }

  function init() {
    var saved = null;
    try { saved = localStorage.getItem(KEY); } catch (e) {}
    var nav = (navigator.language || "fr").toLowerCase();
    var start = saved || (nav.indexOf("nl") === 0 ? "nl" : "fr");
    if (start === "en" || start === "nl") setLang(start, { persist: !!saved });
    else document.querySelectorAll("[data-lang]").forEach(function (b) { b.setAttribute("aria-pressed", String(b.getAttribute("data-lang") === "fr")); });
  }

  window.ZY = window.ZY || {};
  window.ZY.i18n = { t: t, apply: apply, setLang: setLang, get lang() { return lang; } };

  if (document.readyState === "loading") document.addEventListener("DOMContentLoaded", init);
  else init();
